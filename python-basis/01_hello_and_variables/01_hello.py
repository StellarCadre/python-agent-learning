# ============================================================
# 第一个 Python 程序
# ============================================================
# Go 写法：
#   package main
#   import "fmt"
#   func main() { fmt.Println("Hello, World!") }
#
# Python 写法：不需要包声明、不需要 main 函数、不需要导入 fmt，
# 直接 print 即可。
# ============================================================

print("Hello, World!")

# print 默认在末尾换行（等价于 fmt.Println）
print("你好，Python")
print("我正在学习 Agent 开发")

# ---------- print 的多种用法 ----------

# 1. 同时打印多个值，默认用空格分隔
name = "Tom"
age = 18
print("姓名:", name, "年龄:", age)        # 姓名: Tom 年龄: 18

# 2. 修改分隔符 sep
print("2026", "09", "28", sep="-")       # 2026-09-28

# 3. 修改结尾符 end（默认是换行符 \n）
print("第一行", end="")
print("第二行（紧跟在后面）")

# 4. 打印空行
print()

# 5. f-string 格式化输出（最常用，后面字符串章节会详细讲）
print(f"我叫 {name}，今年 {age} 岁")

